export function getQuestionLevel(q) {
  if (q.level) return q.level;
  const d = String(q.difficulty || '');
  if (d.includes('350') || d.includes('450') || d.includes('500')) return 'basic';
  if (d.includes('750') || d.includes('800') || d.includes('990')) return 'advanced';
  return 'intermediate';
}

