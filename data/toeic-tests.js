/**
 * Hàm hỗ trợ xác định cấp độ câu hỏi theo chuẩn FSRS & TOEIC CEFR
 * @param {Object} q Câu hỏi
 * @returns {'basic' | 'intermediate' | 'advanced'}
 */
export function getQuestionLevel(q) {
  if (q.level) return q.level;
  const d = String(q.difficulty || '');
  if (d.includes('350') || d.includes('450') || d.includes('500')) return 'basic';
  if (d.includes('750') || d.includes('800') || d.includes('990')) return 'advanced';
  return 'intermediate';
}

/**
 * Lọc và lấy câu hỏi theo chế độ thi và cấp độ (basic, intermediate, advanced, progressive, all)
 * @param {number} count Số lượng câu hỏi (10, 15, 20, 25, 30)
 * @param {string} mode 'basic' | 'intermediate' | 'advanced' | 'progressive' | 'all'
 * @returns {Array} Danh sách câu hỏi đã được chuẩn hóa và xáo trộn đáp án
 */
export function getRandomToeicQuestions(count = 10, mode = 'all') {
  let pool = [...TOEIC_PART5_BANK];

  if (mode === 'basic') {
    pool = pool.filter(q => getQuestionLevel(q) === 'basic');
  } else if (mode === 'intermediate') {
    pool = pool.filter(q => getQuestionLevel(q) === 'intermediate');
  } else if (mode === 'advanced') {
    pool = pool.filter(q => getQuestionLevel(q) === 'advanced');
  }

  let selected = [];

  if (mode === 'progressive') {
    // Chế độ Lũy tiến chuẩn ETS: Sắp xếp theo thứ tự Căn bản ➔ Trung cấp ➔ Nâng cao
    const basicPool = pool.filter(q => getQuestionLevel(q) === 'basic').sort(() => Math.random() - 0.5);
    const interPool = pool.filter(q => getQuestionLevel(q) === 'intermediate').sort(() => Math.random() - 0.5);
    const advPool = pool.filter(q => getQuestionLevel(q) === 'advanced').sort(() => Math.random() - 0.5);

    // Tỷ lệ phân bổ cấu trúc chuẩn: ~40% Căn bản -> ~40% Trung cấp -> ~20% Nâng cao
    const basicTarget = Math.round(count * 0.4);
    const advTarget = Math.round(count * 0.2);
    const interTarget = count - basicTarget - advTarget;

    const bSlice = basicPool.slice(0, basicTarget);
    const iSlice = interPool.slice(0, interTarget);
    const aSlice = advPool.slice(0, advTarget);

    selected = [...bSlice, ...iSlice, ...aSlice];

    // Bù đắp nếu thiếu
    if (selected.length < count) {
      const remainingPool = pool.filter(q => !selected.some(s => s.id === q.id)).sort(() => Math.random() - 0.5);
      selected = [...selected, ...remainingPool.slice(0, count - selected.length)];
    }
  } else {
    // Xáo trộn ngẫu nhiên trong pool
    const shuffled = pool.sort(() => Math.random() - 0.5);
    selected = shuffled.slice(0, Math.min(count, pool.length));
  }

  // Xáo trộn thứ tự các đáp án trong từng câu hỏi và cập nhật correctIndex tương ứng
  return selected.map((q, idx) => {
    const originalOptions = [...q.options];
    const correctText = originalOptions[q.correctIndex];
    
    const randomizedOptions = [...originalOptions].sort(() => Math.random() - 0.5);
    const newCorrectIndex = randomizedOptions.indexOf(correctText);

    return {
      ...q,
      level: getQuestionLevel(q),
      questionNumber: idx + 1,
      options: randomizedOptions,
      correctIndex: newCorrectIndex
    };
  });
}

/**
 * Quy đổi điểm TOEIC Reading chuẩn theo thang điểm ETS (10 - 495 điểm)
 * @param {number} correctCount Số câu đúng
 * @param {number} totalCount Tổng số câu (10, 20, 30)
 * @returns {Object} { score: number, band: string, levelLabel: string, feedback: string }
 */
export function calculateToeicScore(correctCount, totalCount) {
  const accuracyPct = Math.round((correctCount / Math.max(1, totalCount)) * 100);

  // Bảng quy đổi nội suy điểm Reading TOEIC (Thang 10 - 495)
  let estimatedReadingScore = 10;
  let band = "A1 - Mất gốc";
  let levelLabel = "Cần xây dựng lại nền tảng từ vựng và ngữ pháp cốt lõi.";
  let color = "#ef4444";

  if (accuracyPct >= 95) {
    estimatedReadingScore = 485 + Math.round((accuracyPct - 95) * 2);
    band = "C1 - Chuyên gia TOEIC (850 - 990+)";
    levelLabel = "Khả năng đọc hiểu & phản xạ ngữ pháp hoàn hảo.";
    color = "#10b981";
  } else if (accuracyPct >= 85) {
    estimatedReadingScore = 415 + Math.round(((accuracyPct - 85) / 10) * 70);
    band = "B2+ - Thành thạo nâng cao (785 - 850)";
    levelLabel = "Vốn từ vựng doanh nghiệp phong phú, phản xạ Part 5 rất tốt.";
    color = "#06b6d4";
  } else if (accuracyPct >= 70) {
    estimatedReadingScore = 340 + Math.round(((accuracyPct - 70) / 15) * 75);
    band = "B1+ - Giao tiếp độc lập (650 - 750)";
    levelLabel = "Nắm vững hầu hết cấu trúc ngữ pháp và từ vựng thông dụng.";
    color = "#6366f1";
  } else if (accuracyPct >= 55) {
    estimatedReadingScore = 260 + Math.round(((accuracyPct - 55) / 15) * 80);
    band = "B1 - Sơ trung cấp (500 - 600)";
    levelLabel = "Cần củng cố thêm các bẫy từ loại và cụm giới từ cố định.";
    color = "#f59e0b";
  } else if (accuracyPct >= 40) {
    estimatedReadingScore = 180 + Math.round(((accuracyPct - 40) / 15) * 80);
    band = "A2 - Căn bản (350 - 450)";
    levelLabel = "Cần tăng cường ôn tập từ vựng các chủ đề hợp đồng và quản lý.";
    color = "#f97316";
  } else {
    estimatedReadingScore = 60 + Math.round((accuracyPct / 40) * 120);
    band = "A1 - Khởi đầu (100 - 300)";
    levelLabel = "Hãy duy trì thói quen học flashcard mỗi ngày để tăng tốc độ phản xạ.";
    color = "#ef4444";
  }

  // Giới hạn trong khoảng chuẩn 10 - 495
  estimatedReadingScore = Math.min(495, Math.max(10, Math.round(estimatedReadingScore / 5) * 5));

  return {
    score: estimatedReadingScore,
    accuracyPct,
    band,
    levelLabel,
    color,
    correctCount,
    totalCount
  };
}
