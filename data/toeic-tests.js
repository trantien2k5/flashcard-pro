/**
 * Hàm hỗ trợ xác định cấp độ câu hỏi
 * @param {Object} q Câu hỏi
 * @returns {'basic' | 'intermediate' | 'advanced'}
 */
export function getQuestionLevel(q) {
  if (q.level) return q.level;
  const d = String(q.difficulty || '');
  if (d.includes('350') || d.includes('450') || d.includes('500')) return 'basic';
  if (d.includes('750') || d.includes('800') || d.includes('990')) return 'advanced';
  return 'intermediate';
}

/**
 * Lấy danh sách câu hỏi theo số lượng
 * @param {number} count Số lượng câu hỏi cần lấy
 * @param {boolean} randomize Xáo trộn câu hỏi và đáp án hay không
 * @returns {Array} Danh sách câu hỏi
 */
export function getRandomToeicQuestions(count = 8, randomize = false) {
  let pool = [...TOEIC_PART5_BANK];

  if (randomize) {
    pool.sort(() => Math.random() - 0.5);
  }

  const selected = pool.slice(0, Math.min(count, pool.length));

  return selected.map((q, idx) => {
    let options = [...q.options];
    let correctIdx = q.correctIndex;

    if (randomize) {
      const correctText = options[correctIdx];
      options.sort(() => Math.random() - 0.5);
      correctIdx = options.indexOf(correctText);
    }

    return {
      ...q,
      level: getQuestionLevel(q),
      questionNumber: idx + 1,
      options,
      correctIndex: correctIdx
    };
  });
}

/**
 * Quy đổi điểm TOEIC Reading chuẩn theo thang điểm ETS (10 - 495 điểm)
 * @param {number} correctCount Số câu đúng
 * @param {number} totalCount Tổng số câu
 * @returns {Object} { score: number, band: string, levelLabel: string, feedback: string }
 */
export function calculateToeicScore(correctCount, totalCount) {
  const accuracyPct = Math.round((correctCount / Math.max(1, totalCount)) * 100);

  let estimatedReadingScore = 10;
  let band = "A1 - Mất gốc";
  let levelLabel = "Cần củng cố lại từ vựng và ngữ pháp căn bản.";
  let color = "#ef4444";

  if (accuracyPct >= 95) {
    estimatedReadingScore = 490;
    band = "C1 - Xuất sắc (850 - 990)";
    levelLabel = "Phản xạ ngữ pháp và từ vựng đạt độ chính xác tuyệt đối.";
    color = "#10b981";
  } else if (accuracyPct >= 80) {
    estimatedReadingScore = 420;
    band = "B2 - Nâng cao (750 - 845)";
    levelLabel = "Nắm rất vững ngữ pháp, từ loại và ngữ cảnh Part 5.";
    color = "#06b6d4";
  } else if (accuracyPct >= 65) {
    estimatedReadingScore = 340;
    band = "B1+ - Trung cấp (600 - 700)";
    levelLabel = "Hiểu rõ các câu hỏi từ loại và liên từ thông dụng.";
    color = "#6366f1";
  } else if (accuracyPct >= 50) {
    estimatedReadingScore = 260;
    band = "B1 - Sơ cấp (450 - 550)";
    levelLabel = "Cần chú ý thêm các bẫy ngữ pháp và đại từ quan hệ.";
    color = "#f59e0b";
  } else if (accuracyPct >= 35) {
    estimatedReadingScore = 180;
    band = "A2 - Căn bản (350 - 450)";
    levelLabel = "Hãy duy trì luyện tập hàng ngày để quen dạng câu hỏi.";
    color = "#f97316";
  } else {
    estimatedReadingScore = 100;
    band = "A1 - Khởi đầu (100 - 300)";
    levelLabel = "Cần rèn luyện thêm vốn từ vựng công sở thông dụng.";
    color = "#ef4444";
  }

  return {
    score: estimatedReadingScore,
    accuracyPct,
    band,
    levelLabel,
    color,
    correctCount,
    totalCount
  };
}
