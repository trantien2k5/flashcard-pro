export function getSubtopicIcon(subtopic, fallbackIcon = '📖') {
  if (!subtopic) return fallbackIcon;
  if (SUBTOPIC_ICONS[subtopic]) return SUBTOPIC_ICONS[subtopic];
  
  const lower = subtopic.toLowerCase();
  if (lower.includes('sáng') || lower.includes('morning')) return '🌅';
  if (lower.includes('tối') || lower.includes('đêm') || lower.includes('ngủ') || lower.includes('sleep')) return '🌙';
  if (lower.includes('ăn') || lower.includes('thực phẩm') || lower.includes('món') || lower.includes('food')) return '🍲';
  if (lower.includes('uống') || lower.includes('drink') || lower.includes('nước')) return '🥤';
  if (lower.includes('nhà') || lower.includes('phòng') || lower.includes('home') || lower.includes('living')) return '🏡';
  if (lower.includes('tiền') || lower.includes('mua') || lower.includes('shop') || lower.includes('money')) return '🛍️';
  if (lower.includes('xe') || lower.includes('giao thông') || lower.includes('đi') || lower.includes('transport')) return '🚗';
  if (lower.includes('việc') || lower.includes('công việc') || lower.includes('work') || lower.includes('job')) return '💼';
  if (lower.includes('học') || lower.includes('trường') || lower.includes('thi') || lower.includes('study')) return '🎓';
  if (lower.includes('du lịch') || lower.includes('khách sạn') || lower.includes('travel') || lower.includes('tour')) return '✈️';
  if (lower.includes('nhạc') || lower.includes('phim') || lower.includes('thể thao') || lower.includes('game') || lower.includes('giải trí')) return '🎮';
  if (lower.includes('công nghệ') || lower.includes('web') || lower.includes('app') || lower.includes('tech') || lower.includes('máy tính')) return '💻';
  if (lower.includes('thời tiết') || lower.includes('thiên nhiên') || lower.includes('mùa') || lower.includes('nature')) return '🌦️';
  if (lower.includes('người') || lower.includes('bạn') || lower.includes('gia đình') || lower.includes('people')) return '👥';
  if (lower.includes('cảm xúc') || lower.includes('tâm trạng') || lower.includes('feeling')) return '😊';
  if (lower.includes('sức khỏe') || lower.includes('bệnh') || lower.includes('y tế') || lower.includes('health')) return '❤️';

  return fallbackIcon || '📖';
}
